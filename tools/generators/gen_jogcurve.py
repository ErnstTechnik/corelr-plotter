#!/usr/bin/env python3
"""gen_jogcurve.py -- writes firmware/src/JogCurveTable.h, the shape of the Control jog's speed response.

The table holds f(n) for n = 0, 1/32, ... 1 (n is the stick's deflection beyond the dead zone as a fraction of what is left to the full-scale stop),
as an unsigned 16-bit number: f = 65535 * n^e. The firmware interpolates linearly between entries and multiplies by the maximum speed, so the table
fixes ONLY THE SHAPE: the dead zone, the stick's full scale and the maximum speed are macros and need no new table. e = 2 is the quadratic curve.

  -e EXPONENT   the shape: 1 linear, 2 quadratic (default), 1.5 a gentler top end, 3 cubic
  -o FILE       output (default firmware/src/JogCurveTable.h)
  --check       write nothing; exit 1 if the committed file is not what this would write (tests/host/run_all.sh does this)

Examples:  tools/generators/gen_jogcurve.py            tools/generators/gen_jogcurve.py -e 1.5
"""
import argparse, os
HERE = os.path.dirname(os.path.abspath(__file__))
N = 32

def text(e):
    vals = [round(65535 * (i / N) ** e) for i in range(N + 1)]
    rows = ["   " + ", ".join("%5d" % v for v in vals[k:k + 8]) for k in range(0, N + 1, 8)]
    return ("/* JogCurveTable.h -- GENERATED by tools/generators/gen_jogcurve.py -e %s; do not edit by hand. */\n"
            "/* Copyright (C) 2026 ErnstTechnik and the CoreLR contributors; SPDX-License-Identifier: GPL-3.0-or-later */\n"
            "/* The shape of the Control jog's speed response: f(n) = 65535 * n^%s at n = i/%d (REQ-CoreLR-D-LcdJoystickUI-0021). */\n"
            "#define JOGCURVE_TABLE_STEPS %d\n"
            "static const uint16_t kJogCurve[JOGCURVE_TABLE_STEPS + 1] PROGMEM =\n{\n%s\n};\n") % (("%g" % e), ("%g" % e), N, N, ",\n".join(rows))

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-e", "--exponent", type=float, default=2.0)
    ap.add_argument("-o", "--out", default=os.path.join(HERE, "..", "..", "firmware", "src", "JogCurveTable.h"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    t = text(a.exponent)
    if a.check:
        raise SystemExit(0 if os.path.exists(a.out) and open(a.out).read() == t else 1)
    open(a.out, "w").write(t); print("wrote %s (exponent %g)" % (a.out, a.exponent))

if __name__ == "__main__":
    main()
